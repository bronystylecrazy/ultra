// emitAll renders every file the plugin contributes. genImport is the import
// path of the sqlc output package, which the factory package needs.
func emitAll(tables []tableGen, genImport string) ([]outFile, error) {
	files := []outFile{}
	shared, err := gofmtGo(emitShared(tables))
	if err != nil {
		return nil, err
	}
	files = append(files, outFile{"ultra.go", shared})

	var factories []outFile
	// Every table gets a file even with no constraints and no page query: the
	// 42P01 arm alone is worth a classifier, and its absence would read as a
	// table the plugin failed to see.
	for i := range tables {
		t := &tables[i]
		body, err := gofmtGo(emitTable(t))
		if err != nil {
			return nil, fmt.Errorf("table %s: %w", t.name, err)
		}
		files = append(files, outFile{"ultra_" + t.name + ".go", body})
		if t.noFactory != "" {
			continue
		}
		f, err := gofmtGo(emitFactory(t, genImport))
		if err != nil {
			return nil, fmt.Errorf("factory %s: %w", t.name, err)
		}
		factories = append(factories, outFile{"factory/" + t.name + ".go", f})
	}
	if len(factories) > 0 {
		base, err := gofmtGo(emitFactoryShared())
		if err != nil {
			return nil, err
		}
		files = append(files, outFile{"factory/ultra.go", base})
		files = append(files, factories...)
	}
	return files, nil
}

// writeImports renders the two groups gofmt would not reorder for us —
// stdlib, blank line, everything else — each sorted.
func writeImports(b *strings.Builder, std, ext []string) {
	sort.Strings(std)
	sort.Strings(ext)
	b.WriteString("import (\n")
	for _, p := range std {
		fmt.Fprintf(b, "\t%q\n", p)
	}
	b.WriteString("\n")
	for _, p := range ext {
		fmt.Fprintf(b, "\t%q\n", p)
	}
	b.WriteString(")\n\n")
}

func gofmtGo(src string) ([]byte, error) {
	b, err := format.Source([]byte(src))
	if err != nil {
		return nil, fmt.Errorf("the plugin rendered invalid Go: %w\n%s", err, src)
	}
	return b, nil
}

func emitShared(tables []tableGen) string {
	var b strings.Builder
	b.WriteString(genHeader)
	b.WriteString(`package gen

import (
	"context"
	"errors"

	"github.com/bronystylecrazy/ultrastack/contrib/pg"
	"github.com/jackc/pgx/v5"
)

// DB is the product's one handle on Postgres, and the only thing a Store
// holds. It reaches a querier two ways and no third: Q() for a single
// statement, Atomic() for a unit of work.
type DB struct{ db *pg.DB }

func NewDB(db *pg.DB) *DB { return &DB{db: db} }

// Q is the querier outside a transaction — one statement is already atomic.
func (d *DB) Q() *Queries { return New(d.db.Pool) }

// Atomic runs fn as one transaction: commit when it returns nil, roll back
// otherwise. fn MAY RUN TWICE, because a serialization failure is retried —
// so it must carry no state across the call and do nothing outside the
// database (no publish, no email, no counter).
func (d *DB) Atomic(ctx context.Context, fn func(*Queries) error) error {
	return pg.Atomic(ctx, d.db, func(tx pgx.Tx) error { return fn(New(tx)) })
}

// Tx exposes the handle this querier runs on, so work that must commit WITH
// the caller (jobs.EnqueueTx) joins the transaction instead of opening a
// second one that can commit alone.
func (q *Queries) Tx() DBTX { return q.db }

// ErrSchemaBehind is what 42P01 means in practice: the binary is ahead of the
// database. Every <Table>Error maps it, so no product learns the code.
var ErrSchemaBehind = errors.New("relation does not exist — run ./app migrate up")
`)
	var skipped []string
	for _, t := range tables {
		if t.noFactory != "" {
			skipped = append(skipped, fmt.Sprintf("//   %s — %s", t.name, t.noFactory))
		}
	}
	if len(skipped) > 0 {
		b.WriteString("\n// Tables with no generated factory, and why. Write one by hand in a\n" +
			"// _test file, or give the column a type this generator can default:\n")
		b.WriteString(strings.Join(skipped, "\n"))
		b.WriteString("\n")
	}
	var dropped []string
	for _, t := range tables {
		for _, why := range t.noPages {
			dropped = append(dropped, "//   "+why)
		}
	}
	if len(dropped) > 0 {
		b.WriteString("\n// Keyset queries with no generated <Query>Page wrapper, and why. Call the\n" +
			"// sqlc method directly and fill the cursor params yourself, or drop the\n" +
			"// override that moved them:\n")
		b.WriteString(strings.Join(dropped, "\n"))
		b.WriteString("\n")
	}
	return b.String()
}

func emitTable(t *tableGen) string {
	var b strings.Builder
	b.WriteString(genHeader)
	std, ext := []string{"errors"}, []string{"github.com/jackc/pgx/v5/pgconn"}
	if len(t.pages) > 0 {
		std = append(std, "context", "time")
		ext = append(ext, "github.com/bronystylecrazy/ultrastack/di/diag",
			"github.com/google/uuid", "github.com/jackc/pgx/v5/pgtype")
	}
	b.WriteString("package gen\n\n")
	writeImports(&b, std, ext)

	for _, u := range t.uniques {
		fmt.Fprintf(&b, "// %s is unique constraint %s (%s).\nvar %s = errors.New(%q)\n\n",
			u.sentinel, u.constraint, strings.Join(u.cols, ", "), u.sentinel,
			t.name+": "+strings.Join(u.cols, ", ")+" already taken")
	}

	fmt.Fprintf(&b, `// %sError names what Postgres refused, so a feature branches on a sentinel
// instead of matching driver strings. Anything unrecognized is returned
// UNCHANGED — errors.Is and errors.As still reach the driver error underneath.
func %sError(err error) error {
	var pgErr *pgconn.PgError
	if !errors.As(err, &pgErr) {
		return err
	}
	if pgErr.Code == "42P01" {
		return ErrSchemaBehind
	}
`, t.export, t.export)
	if len(t.uniques) > 0 {
		b.WriteString("\tswitch pgErr.ConstraintName {\n")
		for _, u := range t.uniques {
			fmt.Fprintf(&b, "\tcase %q:\n\t\treturn %s\n", u.constraint, u.sentinel)
		}
		b.WriteString("\t}\n")
	}
	b.WriteString("\treturn err\n}\n")

	for _, p := range t.pages {
		emitPage(&b, t, p)
	}
	return b.String()
}

func emitPage(b *strings.Builder, t *tableGen, p pageGen) {
	// The element type follows sqlc's own rendering: pointers when the
	// product's gen.go says emit_result_struct_pointers.
	elem := p.row
	if t.types.resultPointers {
		elem = "*" + p.row
	}
	fmt.Fprintf(b, `
// %s is one page boundary: the ordering tuple of the last row handed out.
// It is a VALUE, not an offset — a row inserted meanwhile shifts no page.
type %s struct {
	At time.Time
	ID uuid.UUID
}

// %sPage runs %s one row past size, so "is there more" costs no second
// query and no count. A nil cursor starts at the first page.
func (q *Queries) %sPage(ctx context.Context`, p.cursor, p.cursor, p.query, p.query, p.query)
	for _, o := range p.owners {
		fmt.Fprintf(b, ", %s %s", o.arg, o.goType)
	}
	fmt.Fprintf(b, ", after *%s, size int) ([]%s, bool, error) {\n\targ := %s{", p.cursor, elem, p.params)
	for _, o := range p.owners {
		fmt.Fprintf(b, "%s: %s, ", o.field, o.arg)
	}
	fmt.Fprintf(b, `%s: int32(size) + 1}
	if after != nil {
		arg.%s = pgtype.Timestamptz{Time: after.At, Valid: true}
		arg.%s = pgtype.UUID{Bytes: after.ID, Valid: true}
	}
	rows, err := q.%s(ctx, arg)
	if err != nil {
		// Shapes only, never a parameter: a query value can be a person's
		// name or a token, and diag.Wrap's contract is that a fact rides the
		// chain because a caller NAMED it.
		return nil, false, diag.Wrap(%sError(err), "query %s", "size", size, "cursor", after != nil)
	}
	if len(rows) > size {
		return rows[:size], true, nil
	}
	return rows, false, nil
}
`, p.limitField, p.atField, p.idField, p.query, t.export, p.query)
}

func emitFactory(t *tableGen, genImport string) string {
	// The column values come first: which imports the file needs is decided
	// by the literals it ends up holding, and an override can retire the last
	// pgtype in a factory as easily as it can introduce a uuid.
	var fills strings.Builder
	needs := map[string]bool{}
	for _, f := range t.fills {
		fmt.Fprintf(&fills, "\t\t%s: %s,\n", f.field, f.expr)
		for _, imp := range f.needs {
			needs[imp] = true
		}
	}
	std, ext := []string{"context", "testing"}, []string{genImport}
	for imp := range needs {
		if strings.Contains(imp, ".") {
			ext = append(ext, imp)
		} else {
			std = append(std, imp)
		}
	}

	var b strings.Builder
	b.WriteString(genHeader)
	b.WriteString("package factory\n\n")
	writeImports(&b, std, ext)

	// Row spelling follows sqlc's own: *gen.Note when the product's gen.go
	// says emit_result_struct_pointers, gen.Note otherwise.
	row := "gen." + t.model
	if t.types.resultPointers {
		row = "*gen." + t.model
	}
	fmt.Fprintf(&b, `// %s inserts one %s row. Every column the insert demands is filled
// deterministically; the mutators carry the value the test is ABOUT and run
// last, so a test states only what it is testing.
func %s(t testing.TB, db gen.DBTX, mut ...func(*gen.%sParams)) %s {
	t.Helper()
	n := next(t, %q)
	arg := gen.%sParams{
`, t.model, t.name, t.model, t.create.Name, row, t.name, t.create.Name)

	b.WriteString(fills.String())
	fmt.Fprintf(&b, `	}
	for _, m := range mut {
		m(&arg)
	}
	row, err := gen.New(db).%s(context.Background(), arg)
	if err != nil {
		t.Fatalf("factory.%s: %%v", err)
	}
	return row
}

// %sN inserts count rows, ascending — the shape a paging test wants.
func %sN(t testing.TB, db gen.DBTX, count int, mut ...func(*gen.%sParams)) []%s {
	t.Helper()
	rows := make([]%s, 0, count)
	for range count {
		rows = append(rows, %s(t, db, mut...))
	}
	return rows
}
`, t.create.Name, t.model, t.model, t.model, t.create.Name, row, row, t.model)
	return b.String()
}

func emitFactoryShared() string {
	return genHeader + `// Package factory builds rows the schema will accept, so a test can state
// only what it is actually about. Import it from _test files ONLY — it links
// testing, and test-only code must never reach the product binary.
package factory

import (
	"encoding/binary"
	"hash/fnv"
	"sync"
	"sync/atomic"
	"testing"
	"time"

	"github.com/jackc/pgx/v5/pgtype"
)

// epoch anchors every generated timestamp: fixed, so an assertion can name a
// value, and ascending by sequence, so rows page in insertion order.
var epoch = time.Date(2020, 1, 1, 0, 0, 0, 0, time.UTC)

func at(n int64) time.Time { return epoch.Add(time.Duration(n) * time.Second) }

// ptr fills a NULLABLE column: with emit_pointers_for_null_types sqlc spells
// those *T, and a factory always has a value to point at.
func ptr[T any](v T) *T { return &v }

// seqs is the per-test, per-table counter. Keying on the testing.TB is what
// makes parallel tests independent; the cleanup keeps a long package run from
// retaining every test that ever asked for a row.
var seqs sync.Map // seqKey -> *atomic.Int64

type seqKey struct {
	t     testing.TB
	table string
}

func next(t testing.TB, table string) int64 {
	key := seqKey{t, table}
	v, loaded := seqs.LoadOrStore(key, new(atomic.Int64))
	if !loaded {
		t.Cleanup(func() { seqs.Delete(key) })
	}
	return v.(*atomic.Int64).Add(1)
}

// uuidAt is a deterministic v4-shaped UUID: the table name mixed into the
// high half, the sequence in the low half, so two tables' first rows differ.
func uuidAt(table string, n int64) pgtype.UUID {
	h := fnv.New64a()
	h.Write([]byte(table))
	var b [16]byte
	binary.BigEndian.PutUint64(b[:8], h.Sum64())
	binary.BigEndian.PutUint64(b[8:], uint64(n))
	b[6] = b[6]&0x0f | 0x40
	b[8] = b[8]&0x3f | 0x80
	return pgtype.UUID{Bytes: b, Valid: true}
}
`
}
