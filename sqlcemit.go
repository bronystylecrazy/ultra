package main

// What the ultra sqlc plugin writes.
//
// sqlc's own Go codegen answers "what do these queries look like in Go". It
// stops exactly where every product then writes the same four things by hand:
// a handle that can open a transaction, a bridge for work that must commit
// with the caller, keyset paging around a cursor query, and test rows the
// schema will accept. Those four are DERIVABLE from the schema sqlc already
// parsed, so they are generated here rather than remembered per product.
//
// Nothing in this file guesses: a wrapper appears when a query's compiled
// shape proves it is a keyset page, a sentinel appears when the migration
// declares the constraint, a factory appears when every column its insert
// demands has a deterministic value IN THE TYPE SQLC EMITTED for it
// (sqlcoverride.go resolves that). A table that fails a test gets NO output
// and a named reason in ultra.go — silence would be the one failure mode worse
// than the hand-written code this replaces.

import (
	"cmp"
	"fmt"
	"go/format"
	"regexp"
	"slices"
	"sort"
	"strings"
	"unicode"
)

// genHeader tops every emitted file. It says which tool and which command —
// an agent that finds this file must not edit it, and must know the verb.
const genHeader = "// Code generated by sqlc (ultra plugin). DO NOT EDIT — regenerate: sqlc generate\n\n"

// pgType is one Postgres type's TWO Go renderings under sqlc's pgx/v5 driver:
// what a NOT NULL column gets, and what a nullable one gets. Both are sqlc's
// answers, transcribed from real output rather than invented here — a factory
// only compiles if it agrees with the params struct beside it. A type absent
// from this table is not guessed: its table loses its factory and says why.
type pgType struct {
	notNull string
	null    string
	// pointer reports whether emit_pointers_for_null_types moves the nullable
	// rendering to *notNull. pgx/v5 keeps uuid, the date/time family and the
	// []byte types on their own spelling either way, so the flag is per type.
	pointer bool
}

const pgtypePkg = "github.com/jackc/pgx/v5/pgtype"

