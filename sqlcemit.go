// factoryValue is a deterministic value of goType — the type sqlc RESOLVED for
// this column, whatever route it took there. dbType only ever chooses between
// two values of one Go type (a json column must hold valid JSON; a bytea is
// happier holding the row's own name). needs is what the expression refers to,
// so a file's imports follow the literals it ended up with. ok is false for a
// type this generator has no defensible value for — the caller reports that
// instead of writing something that will not compile.
func factoryValue(goType, imp, dbType, table, col, seq string) (expr string, needs []string, ok bool) {
	if base, isPtr := strings.CutPrefix(goType, "*"); isPtr {
		expr, needs, ok := factoryValue(base, imp, dbType, table, col, seq)
		return "ptr(" + expr + ")", needs, ok
	}
	str := fmt.Sprintf("fmt.Sprintf(%q, %s)", table+"-"+col+"-%d", seq)
	switch goType {
	case "string":
		return str, []string{"fmt"}, true
	case "bool":
		return "false", nil, true
	case "int16":
		return "int16(" + seq + ")", nil, true
	case "int32":
		return "int32(" + seq + ")", nil, true
	case "int64":
		return seq, nil, true
	case "float32":
		return "float32(" + seq + ")", nil, true
	case "float64":
		return "float64(" + seq + ")", nil, true
	case "[]byte":
		if dbType == "json" || dbType == "jsonb" {
			return `[]byte("{}")`, nil, true
		}
		return "[]byte(" + str + ")", []string{"fmt"}, true
	case "pgtype.Text":
		return "pgtype.Text{String: " + str + ", Valid: true}", []string{"fmt", pgtypePkg}, true
	case "pgtype.Bool":
		return "pgtype.Bool{Bool: false, Valid: true}", []string{pgtypePkg}, true
	case "pgtype.Int2":
		return "pgtype.Int2{Int16: int16(" + seq + "), Valid: true}", []string{pgtypePkg}, true
	case "pgtype.Int4":
		return "pgtype.Int4{Int32: int32(" + seq + "), Valid: true}", []string{pgtypePkg}, true
	case "pgtype.Int8":
		return "pgtype.Int8{Int64: " + seq + ", Valid: true}", []string{pgtypePkg}, true
	case "pgtype.Float4":
		return "pgtype.Float4{Float32: float32(" + seq + "), Valid: true}", []string{pgtypePkg}, true
	case "pgtype.Float8":
		return "pgtype.Float8{Float64: float64(" + seq + "), Valid: true}", []string{pgtypePkg}, true
	case "pgtype.UUID":
		// uuidAt is factory-local and already returns a pgtype.UUID, so this
		// spelling costs the file no import of its own.
		return fmt.Sprintf("uuidAt(%q, %s)", table, seq), nil, true
	case "pgtype.Timestamptz":
		return "pgtype.Timestamptz{Time: at(" + seq + "), Valid: true}", []string{pgtypePkg}, true
	case "pgtype.Timestamp":
		return "pgtype.Timestamp{Time: at(" + seq + "), Valid: true}", []string{pgtypePkg}, true
	case "pgtype.Date":
		return "pgtype.Date{Time: at(" + seq + "), Valid: true}", []string{pgtypePkg}, true
	case "time.Time":
		// at() is factory-local too, so a time.Time fill needs no import.
		return "at(" + seq + ")", nil, true
	case "uuid.UUID":
		// uuid.UUID is [16]byte, so the deterministic value already on hand
		// converts without a second generator.
		if imp == "" {
			imp = "github.com/google/uuid"
		}
		return fmt.Sprintf("uuid.UUID(uuidAt(%q, %s).Bytes)", table, seq), []string{imp}, true
	}
	return "", nil, false
}

// ---- the analysis ----

// tableGen is everything the emitter concluded about one table.
type tableGen struct {
	name   string // the SQL table, "notes"
	ident  sqlcIdent
	model  string // sqlc's row struct, "Note"
	export string // the plural Go stem for this table's symbols, "Notes"
	cols   []sqlcColumn

	uniques []uniqueGen
	pages   []pageGen
	create  *sqlcQuery        // the insert this table's factory drives
	fkByCol map[string]string // column -> the parent table a factory must create first
	// types is the product's type policy, shared by every table in one run:
	// this sqlc.yaml's overrides and its nullable rendering.
	types typeConfig
	// fills is what the factory sets, resolved once in planFactory so the
	// emitter and the refusal below can never be two opinions about a column.
	fills []colFill
	// noFactory, when set, is the reason — reported in ultra.go rather than
	// swallowed, so "where is my factory" is never a mystery.
	noFactory string
	// noPages is the same channel for a query that IS a keyset page but got no
	// wrapper: "<Query> — <reason>", one per dropped query. Refusing is right;
	// refusing quietly is the mystery this generator exists to avoid.
	noPages []string
}

// colFill is one column a factory sets, already spelled in the type sqlc
// emitted for it.
type colFill struct {
	field string
	expr  string
	needs []string
}

type uniqueGen struct {
	constraint string // exactly what pgconn.PgError.ConstraintName carries
	sentinel   string // ErrNotesSubjectTaken
	cols       []string
}

// pageGen is one query whose compiled shape IS a keyset page.
type pageGen struct {
	query                        string // ListNotes
	cursor                       string // NotesCursor
	row                          string // the element type of the generated method's result
	params                       string // ListNotesParams
	atField, idField, limitField string
	owners                       []ownerArg
}

type ownerArg struct {
	arg    string // the Go parameter, lower camel
	field  string // the params struct field
	goType string
}

// analyze turns a decoded request plus the schema facts scraped from the
// migrations into the per-table plan the emitters render.
func analyze(req *sqlcRequest, facts schemaFacts, types typeConfig) []tableGen {
	var out []tableGen
	for _, s := range req.Catalog.Schemas {
		if s.Name != types.schema {
			continue // pg_catalog and friends ride along in every request
		}
		for _, t := range s.Tables {
			g := tableGen{
				name:    t.Rel.Name,
				ident:   t.Rel,
				model:   modelName(t.Rel.Name),
				export:  goName(t.Rel.Name),
				cols:    t.Columns,
				fkByCol: facts.fks[t.Rel.Name],
				types:   types,
			}
			for _, u := range facts.uniques[g.name] {
				g.uniques = append(g.uniques, uniqueGen{
					constraint: u.name,
					sentinel:   sentinelName(u),
					cols:       u.cols,
				})
			}
			out = append(out, g)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].name < out[j].name })

	byName := map[string]*tableGen{}
	for i := range out {
		byName[out[i].name] = &out[i]
	}
	for i := range req.Queries {
		q := &req.Queries[i]
		if q.InsertIntoTable != nil {
			if g := byName[q.InsertIntoTable.Name]; g != nil && g.create == nil && q.Cmd == ":one" {
				g.create = q
			}
			continue
		}
		p, table, reason := detectPage(q, byName, types)
		switch {
		case p != nil:
			table.pages = append(table.pages, *p)
		case reason != "":
			table.noPages = append(table.noPages, fmt.Sprintf("%s — %s", q.Name, reason))
		}
	}
	for i := range out {
		out[i].fills, out[i].noFactory = planFactory(&out[i], byName)
	}
	return out
}

// sentinelName turns a constraint into a Go sentinel: notes_subject_key
// becomes ErrNotesSubjectTaken. The DB object's own name is the source, so
// the sentinel and the error Postgres reports can never drift apart.
func sentinelName(u uniqueFact) string {
	stem := u.name
	for _, suffix := range []string{"_key", "_idx", "_index", "_unique", "_uniq", "_uq"} {
		stem = strings.TrimSuffix(stem, suffix)
	}
	return "Err" + goName(stem) + "Taken"
}

// tupleRe finds a keyset tuple compare: (created_at, id) < (…, …).
var tupleRe = regexp.MustCompile(`\(\s*(\w+)\s*,\s*(\w+)\s*\)\s*[<>]\s*\(`)

// detectPage reports whether a compiled query IS a keyset page over one
// table: a :many with a nullable (timestamptz, uuid) narg pair compared as a
// tuple against the columns it orders by, plus an integer limit. Shape, not
// naming — a query that merely mentions a cursor gets nothing.
func detectPage(q *sqlcQuery, byName map[string]*tableGen, types typeConfig) (*pageGen, *tableGen, string) {
	if q.Cmd != ":many" || len(q.Columns) == 0 {
		return nil, nil, ""
	}
	tuple := tupleRe.FindStringSubmatch(strings.ToLower(q.Text))
	if tuple == nil || !strings.Contains(strings.ToLower(q.Text), "order by") {
		return nil, nil, ""
	}
	var at, id, limit *sqlcColumn
	var owners []sqlcColumn
	for i := range q.Params {
		c := q.Params[i].Column
		switch {
		case c.IsNamedParam && !c.NotNull && baseType(c.Type.Name) == "timestamptz" && at == nil:
			at = &q.Params[i].Column
		case c.IsNamedParam && !c.NotNull && baseType(c.Type.Name) == "uuid" && id == nil:
			id = &q.Params[i].Column
		case !c.IsNamedParam && isIntType(baseType(c.Type.Name)) && limit == nil:
			limit = &q.Params[i].Column
		default:
			owners = append(owners, c)
		}
	}
	if at == nil || id == nil || limit == nil {
		return nil, nil, ""
	}
	// The tuple must be the ORDER BY, or the "one row past the end" trick
	// reads a page nobody asked for.
	order := strings.ToLower(q.Text[strings.LastIndex(strings.ToLower(q.Text), "order by"):])
	if !strings.Contains(order, tuple[1]) || !strings.Contains(order, tuple[2]) {
		return nil, nil, ""
	}
	table := byName[q.Columns[0].Table.GetName()]
	if table == nil {
		return nil, nil, ""
	}
	// emitPage writes the cursor into the two narg fields as pgtype literals,
	// so a product whose overrides moved them elsewhere gets no wrapper rather
	// than one that does not compile. From here on the table is known, so the
	// refusal carries its reason instead of vanishing.
	if atType, _ := types.goTypeOf(at.Table, *at); atType != "pgtype.Timestamptz" {
		return nil, table, fmt.Sprintf("the cursor param %s is %s, not pgtype.Timestamptz — an override moved it", at.Name, atType)
	}
	if idType, _ := types.goTypeOf(id.Table, *id); idType != "pgtype.UUID" {
		return nil, table, fmt.Sprintf("the cursor param %s is %s, not pgtype.UUID — an override moved it", id.Name, idType)
	}
	p := pageGen{
		query:      q.Name,
		cursor:     strings.TrimPrefix(q.Name, "List") + "Cursor",
		row:        rowType(q, table),
		params:     q.Name + "Params",
		atField:    goName(at.Name),
		idField:    goName(id.Name),
		limitField: goName(limit.Name),
	}
	for _, c := range owners {
		goType, _ := types.goTypeOf(c.Table, c)
		if goType == "" || !c.NotNull || c.IsArray {
			// An owner we cannot type is not a page we can write — and that is
			// worth saying, for the same reason the cursor checks above are.
			return nil, table, fmt.Sprintf("the filter param %s is %s — a page wrapper cannot pass it through", c.Name, cmp.Or(goType, c.Type.Name))
		}
		p.owners = append(p.owners, ownerArg{arg: lowerCamel(goName(c.Name)), field: goName(c.Name), goType: goType})
	}
	return &p, table, ""
}

// rowType is the element type of the generated method's slice: sqlc reuses
// the table's model when a query returns that table's columns unchanged
// (`select *`), and mints <Query>Row otherwise.
func rowType(q *sqlcQuery, t *tableGen) string {
	if len(q.Columns) != len(t.cols) {
		return q.Name + "Row"
	}
	for i, c := range q.Columns {
		if c.Name != t.cols[i].Name || c.Table.GetName() != t.name {
			return q.Name + "Row"
		}
	}
	return t.model
}

func (i *sqlcIdent) GetName() string {
	if i == nil {
		return ""
	}
	return i.Name
}

// planFactory resolves what this table's factory fills, or the reason it gets
// none. Every column goes through typeConfig.goTypeOf — the same resolution
// sqlc ran for the params struct — so an override, a nullable column, or a
// foreign key whose parent id is spelled differently is decided HERE, once,
// and the emitter only renders the answer.
func planFactory(t *tableGen, byName map[string]*tableGen) ([]colFill, string) {
	if t.create == nil {
		return nil, "no :one insert query — a factory has nothing to call"
	}
	var fills []colFill
	for _, p := range t.create.Params {
		c := p.Column
		if c.IsArray {
			return nil, fmt.Sprintf("column %s is an array — no defensible default", c.Name)
		}
		goType, imp := t.types.goTypeOf(&t.ident, c)
		if goType == "" {
			return nil, fmt.Sprintf("column %s is %s, which has no deterministic default", c.Name, c.Type.Name)
		}
		if parent := t.fkByCol[c.Name]; parent != "" {
			expr, reason := parentFill(t, byName, parent, c.Name, goType)
			if reason != "" {
				return nil, reason
			}
			fills = append(fills, colFill{field: goName(c.Name), expr: expr})
			continue
		}
		expr, needs, ok := factoryValue(goType, imp, baseType(c.Type.Name), t.name, c.Name, "n")
		if !ok {
			return nil, fmt.Sprintf("column %s is %s (%s in Go), which has no deterministic default", c.Name, c.Type.Name, goType)
		}
		fills = append(fills, colFill{field: goName(c.Name), expr: expr, needs: needs})
	}
	return fills, ""
}

// parentFill takes a foreign key from a row the factory creates first. The two
// sides must be spelled the SAME way — an override or a nullable column can
// give a child's fk a type its parent's id does not have, and a conversion
// this generator invented would be a guess.
func parentFill(t *tableGen, byName map[string]*tableGen, parent, col, goType string) (expr, reason string) {
	g := byName[parent]
	switch {
	case parent == t.name:
		return "", fmt.Sprintf("column %s references its own table — a factory would not terminate", col)
	case g == nil || g.create == nil:
		return "", fmt.Sprintf("column %s references %s, which has no factory of its own", col, parent)
	}
	i := slices.IndexFunc(g.cols, func(p sqlcColumn) bool { return p.Name == "id" })
	if i < 0 {
		return "", fmt.Sprintf("column %s references %s, which has no id column to take", col, parent)
	}
	id, _ := g.types.goTypeOf(&g.ident, g.cols[i])
	take := modelName(parent) + "(t, db).ID"
	switch goType {
	case id:
		return take, ""
	case "*" + id:
		return "ptr(" + take + ")", ""
	}
	return "", fmt.Sprintf("column %s is %s but %s.id is %s — a factory cannot bridge them", col, goType, parent, id)
}

func baseType(s string) string {
	if i := strings.LastIndex(s, "."); i >= 0 {
		s = s[i+1:]
	}
	return strings.ToLower(s)
}

func isIntType(s string) bool {
	switch s {
	case "int2", "int4", "int8", "smallint", "integer", "bigint":
		return true
	}
	return false
}

func lowerCamel(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	// An initialism keeps its shape until the first lowercase run: IDToken
	// becomes idToken, ID becomes id.
	i := 0
	for i < len(r) && unicode.IsUpper(r[i]) {
		i++
	}
	if i > 1 && i < len(r) {
		i--
	}
	for j := 0; j < i; j++ {
		r[j] = unicode.ToLower(r[j])
	}
	return goKeyword(string(r))
}

// goKeyword keeps a column named `type` or `range` from becoming an illegal
// parameter name.
func goKeyword(s string) string {
	switch s {
	case "break", "case", "chan", "const", "continue", "default", "defer", "else",
		"fallthrough", "for", "func", "go", "goto", "if", "import", "interface",
		"map", "package", "range", "return", "select", "struct", "switch", "type", "var":
		return s + "_"
	}
	return s
}

